import { Request, Response } from 'express'
import { isArray } from 'lodash'
import { db } from '../db-connection'
import { EmailStatus } from '../constants'
import { addEmailToNotion } from '../notion/notion'
import { shouldDeliverToNotion } from '../notion/shouldDeliverToNotion'
import {
  addContactToNotion,
  maybeUpdateContactsPageProperties,
} from '../notion/addContactToNotion'
import {
  objectCamelToSnake,
  headerMapToArray,
  parseHeaderString,
  getFullNameFromEmailToStr,
} from '../utils'
import { FREE_TIER_EMAIL_LIMIT } from '../constants'
import { storeFiles } from '../s3/storeFiles'
import type { MulterFile } from '../types/shared'
import type { EmailAttachment } from '../types/database'
import { getNotionClient } from '../notion/getNotionClient'

interface InboundSendgridParsedEmail {
  userId?: string
  subject: string
  plainTextContent: string
  from: string
  emailId?: number
  emailThreadId?: number
  htmlContent?: string
  status?: string
  notionPageId?: string
  messageId?: string
  inReplyTo?: string
  references?: string
  createdAt: string
}

export async function emailReceiveHandler(req: Request, res: Response) {
  const { body } = req
  const { headers, from, subject, text, html, envelope: envelopeStr } = body

  // req.body contains:
  // - headers
  // - dkim
  // - to -> sometimes "to" can be formatted like this: "to": "Matt Ehlinger <ehlinger.matt@gmail.com>"
  // - cc
  // - html
  // - from -> sometimes "to" can be formatted like this: "from": "Matt Ehlinger <ehlinger.matt@gmail.com>"
  // - text
  // - sender_ip
  // - spam_report
  // - envelope
  // - attachments
  // - subject
  // - spam_score
  // - charsets
  // - SP

  // @ts-ignore
  const files = await storeFiles(req.files as Array<MulterFile>)

  const headersMap = parseHeaderString(headers)

  const inReplyTo = headersMap['in-reply-to']
  const references = headersMap['references']
  const messageID = headersMap['message-id']

  let envelope = { to: [], from: '' }
  try {
    envelope = JSON.parse(envelopeStr)
  } catch (err) {
    console.error('error parsing incoming email envelope JSON', err)
  }

  let toAddresses = envelope?.to || []
  if (!isArray(toAddresses)) {
    toAddresses = [toAddresses]
  }

  for (let to of toAddresses) {
    to = to.toLowerCase()
    let emailRecipient

    try {
      emailRecipient = await db
        .users()
        .where('email_address', to)
        .select('*')
        .first()
    } catch (err) {
      console.error('error querying for email recipient', err)
    }

    const incomingEmail: InboundSendgridParsedEmail = {
      subject,
      from,
      plainTextContent: text,
      htmlContent: html,
      createdAt: new Date().toISOString(),
    }

    if (references) {
      incomingEmail.references = references[0]
    }

    if (inReplyTo) {
      incomingEmail.references = inReplyTo[0]
    }

    if (messageID) {
      incomingEmail.messageId = messageID[0]
    }

    if (!emailRecipient) {
      incomingEmail.status = EmailStatus.RECEIVED_TO_DECO__TO_ADDRESS_NOT_FOUND

      try {
        const newEmail = await db
          .emails()
          .insert(
            objectCamelToSnake(incomingEmail),
            ['id']
          )
          .first()

        await db
          .emailHeaders()
          .insert(
            headerMapToArray(headersMap, newEmail.id).map((header) =>
              objectCamelToSnake(header),
            ),
          )
      } catch (err) {
        console.error('error inserting email', err)
      }

      continue
    }

    incomingEmail.userId = emailRecipient.id
    incomingEmail.status = EmailStatus.RECEIVED_TO_DECO

    // TODO: compose threads rather than creating a new one for each new email
    let newEmailThread

    try {
      const [thread] = await db.emailThreads().returning('*').insert({
        subject,
        user_id: emailRecipient.id,
      })

      newEmailThread = thread
    } catch (err) {
      console.error(err)
    }

    incomingEmail.emailThreadId = newEmailThread?.id

    let newEmail
    try {
      const [email] = await db
        .emails()
        .insert(objectCamelToSnake(incomingEmail))
        .returning('*')

      newEmail = email
      incomingEmail.emailId = email.id
      incomingEmail.createdAt = email.createdAt
    } catch (err) {
      console.error(err)
    }

    let preppedFiles: Array<EmailAttachment> = files.map((file) => {
      return {
        userfrontUserId: emailRecipient.userfrontUserId,
        uuid: file.uuid,
        filename: file.originalname,
        encoding: file.encoding,
        mimetype: file.mimetype,
        size: file.size,
        emailId: newEmail.id,
      }
    })
    try {
      // passing an empty array here causes the insert to fail
      if (preppedFiles.length > 0) {
        // reassign so that we have the id generated by Postgres stored in each "prepped file"
        preppedFiles = await db.emailAttachments()
          .insert(preppedFiles.map(objectCamelToSnake))
          .returning('*')
      }
    } catch (err) {
      console.error('error inserting email attachments', err)
    }

    let emailStatus = EmailStatus.RECEIVED_TO_DECO
    let notionPageId = null

    const shouldDeliver = await shouldDeliverToNotion(
      emailRecipient.userfrontUserId,
    )

    if (shouldDeliver) {
      try {
        const notionClient = await getNotionClient(
          emailRecipient.userfrontUserId,
        )

        const notionContactResp = await addContactToNotion({
          userfrontID: emailRecipient.userfrontUserId,
          email: envelope.from,
          fullName: getFullNameFromEmailToStr(from),
          notionClient,
        })

        const notionEmailResp = await addEmailToNotion({
          newEmail: incomingEmail,
          userfrontID: emailRecipient.userfrontUserId,
          attachments: preppedFiles,
          notionContactsDatabaseId: notionContactResp?.notionContactsDatabaseId,
          notionContactPage: notionContactResp?.contactPage,
          notionClient,
        })

        // re update page properties with notion rollup and relation. This is important because these cannot be
        // created until the email is created.
        if (notionContactResp) {
          await maybeUpdateContactsPageProperties({
            notionContactsDatabaseId:
              notionContactResp?.notionContactsDatabaseId,
            notionEmailDatabaseId: notionEmailResp.notionEmailDatabaseId,
            notionClient,
          })
        }

        if (notionEmailResp?.pageId) {
          emailStatus = EmailStatus.RECEIVED_TO_NOTION
          notionPageId = notionEmailResp.pageId
        }
      } catch (err) {
        emailStatus = EmailStatus.RECEIVED_TO_DECO__NOTION_IMPORT_FAILED
        console.error(err)
      }
    } else {
      emailStatus = EmailStatus.RECEIVED_TO_DECO__FREE_TIER_LIMIT_EXCEEDED

      console.warn(
        `warn: email not delivered to Notion because ${toAddresses} does not have an active subscription or has exceeded their free tier limit of ${FREE_TIER_EMAIL_LIMIT} emails in their inbox`,
      )
    }

    try {
      await db
        .emails()
        .where('id', newEmail.id)
        .update(
          objectCamelToSnake({
            status: emailStatus,
            notionPageId,
          }),
        )
    } catch (err) {
      console.error('error updating email status', err)
    }

    try {
      await db
        .emailHeaders()
        .insert(
          headerMapToArray(headersMap, newEmail.id).map((header) =>
            objectCamelToSnake(header),
          ),
        )
    } catch (err) {
      console.error('error inserting email headers', err)
    }
  }

  // sendgrid requires a 200 response regardless of success or failure or else it will continually retry
  // thus, we need to signal to sendgrid that we got the email and do not require an additional retry
  res.status(200).json({ message: 'success' })
}
